function pick(device: string, description: string): string[] {
  const text = `${device} ${description}`.toLowerCase();
  const deviceRules = BY_DEVICE[device] ?? [];
  const hits = [...deviceRules, ...COMMON]
    .filter((rule) => rule.keywords.some((word) => text.includes(word.toLowerCase()))
    )
    .flatMap((rule) => rule.tips);

  const unique = Array.from(new Set(hits)).slice(0, 3);
  const generic: Record<string, string[]> = {
    打印机: [
      "确认打印机面板是否有报错代码，记录代码后再继续排查。",
      "重启打印机与电脑，重新添加打印队列后再试一次。",
      "打印测试页确认是单机问题还是整个办公区共享问题。",
    ],
    投影仪: [
      "确认信号源（HDMI/无线投屏）选择正确，线缆两端插紧。",
      "重启投影仪与信号源设备，等待 1 分钟再连接。",
      "记录故障发生时的画面现象，便于工程师远程判断。",
    ],
    电脑: [
      "保存工作后重启一次，观察故障是否复现。",
      "检查系统更新与驱动是否为最新版本。",
      "记录报错原文或截图，提交工单时一并附上。",
    ],
  };
  const base = generic[device] ?? generic.电脑;

  return [...unique, ...base].slice(0, 3);
}

export function fallbackSuggestions(device: string, description: string): string[] {
  return pick(device, description);
}
